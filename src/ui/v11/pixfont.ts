const MAC: Record<string, string> = { Ā: 'A', Ē: 'E', Ī: 'I', Ō: 'O', Ū: 'U', ā: 'a', ē: 'e', ī: 'i', ō: 'o', ū: 'u' };
// ī: the dot becomes a bar, so it needs a little more room
G['ī'] = ['###', '...', '.#.', '.#.', '.#.', '.#.', '.#.'];

/** line height at 1x: two rows for a capital macron, 7 cap rows, 2 descender rows, a gap */
export const PX_LH = 12;
/** cap top within a line */
const TOP = 2;

export interface PxOpts { scale?: number; bold?: boolean; shadow?: C; maxW?: number; lh?: number; align?: 'left' | 'center' | 'right' }

const glyph = (ch: string) => G[ch] ?? G[MAC[ch] ?? ''] ?? G[ch.normalize('NFD')[0]] ?? G['?'];
const gw = (ch: string) => glyph(ch)[0].length;

export function pxWidth(text: string, o: PxOpts = {}): number {
  const s = o.scale ?? 1;
  let w = 0;
  const adv = o.bold ? 2 : 1;
  for (const ch of text) w += gw(ch) + (ch === ' ' ? 1 : adv);
  return Math.max(0, (w - adv) * s + (o.bold ? s : 0));
}
/** word-wrap to a width (px, at the given scale) */
export function pxWrap(text: string, maxW: number, o: PxOpts = {}): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (pxWidth(t, o) <= maxW || !line) line = t;
      else { out.push(line); line = word; }
    }
    out.push(line);
  }
  return out;
}
/** draw one line (no wrapping) */
function drawLine(b: PixelBuffer, text: string, x: number, y: number, c: C, o: PxOpts) {
  const s = o.scale ?? 1;
  const put = (px: number, py: number, col: C) => {
    for (let dy = 0; dy < s; dy++) for (let dx = 0; dx < s; dx++) b.set(px + dx, py + dy, col);
  };
  const pass = (col: C, ox: number, oy: number) => {
    let cx = x;
    for (const ch of text) {
      const g = glyph(ch), w = g[0].length;
      const mac = MAC[ch] !== undefined && ch !== 'ī';
      for (let r = 0; r < g.length; r++) for (let k = 0; k < w; k++) if (g[r][k] === '#') {
        put(cx + (k + ox) * s, y + (TOP + r + oy) * s, col);
        if (o.bold) put(cx + (k + 1 + ox) * s, y + (TOP + r + oy) * s, col);
      }
      if (mac) {
        // a macron: over the cap (two rows up) or over the x-height
        const upper = ch === ch.toUpperCase();
        const my = upper ? TOP - 2 : TOP;
        for (let k = 0; k < w; k++) put(cx + (k + ox) * s, y + (my + oy) * s, col);
        if (o.bold) put(cx + (w + ox) * s, y + (my + oy) * s, col);
      }
      cx += (w + (o.bold && ch !== ' ' ? 2 : 1)) * s;
    }
  };
  if (o.shadow !== undefined) pass(o.shadow, 0, 1);
  pass(c, 0, 0);
}
/** draw text (wrapped to maxW if given); returns the height used */
export function drawPx(b: PixelBuffer, text: string, x: number, y: number, c: C, o: PxOpts = {}): number {
  const s = o.scale ?? 1, lh = (o.lh ?? PX_LH) * s;
  const lines = o.maxW ? pxWrap(text, o.maxW, o) : text.split('\n');
  lines.forEach((ln, i) => {
    let lx = x;
    if (o.align && o.maxW) { const w = pxWidth(ln, o); lx = o.align === 'center' ? x + Math.floor((o.maxW - w) / 2) : o.align === 'right' ? x + o.maxW - w : x; }
    drawLine(b, ln, lx, y + i * lh, c, o);
  });
  return lines.length * lh;
}
